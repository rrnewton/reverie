#!/bin/bash
# Install the PATH shim herdr-run needs to reach ci-hub.
#
# WHY A SHIM AT ALL: herdr-run resolves programs as BARE NAMES from PATH -- it
# refuses a path argument ("program must be a bare command name"). A symlink
# does not work either: ci-hub is a rust-script and resolves
# `mod history_queries;` relative to the script's own path, so a link makes it
# look for <linkdir>/lib/ and fail to compile.
#
# WHY THE NAME IS `ci-hub-cli` AND NOT `ci-hub`: herdr-run executes in the
# PARENT repo, which contains a `ci-hub/` DIRECTORY. When the shim goes missing,
# the bare name `ci-hub` resolves to that directory and exec fails with
# "cannot execute: Is a directory" -- and in at least one observed case the
# command produced NO OUTPUT AT ALL, which an unwary caller reads as a clean
# empty result rather than a broken query. A name with no directory of the same
# name cannot be shadowed, so the failure mode is removed rather than handled.
#
# WHY validate-run TAKES A DIFFERENT PATH: every other subcommand runs the
# parent checkout's ci-hub, and the parent checkout drifts behind origin/main
# (176 commits behind on 2026-10-01). validate-run is the one subcommand that
# launches work, so it goes through the installed operational-tool instead.
# That launcher materializes the current origin/main tooling under
# ~/.local/state/hermit-health-tool, runs that copy's ci-hub, and defaults
# FLEET_REAL_GH to ~/bin/gh, which validate-run requires and a Herdr pane does
# not set. ci-hub/landing/pr_head_ci.py launches validation the same way.
# `--state-root` is given to validate-run as well as to the launcher; ci-hub
# also forwards the launcher's DEV_HERMIT_PARENT, and both name the same root.
#
# WHY THE SHIM NAMES THE MAIN WORKTREE: the root is derived from the git common
# directory, not from this script's own checkout, so running the installer
# from a disposable linked worktree cannot leave the shim pointing into a
# directory that is about to be removed.
#
# Idempotent. Run it if `ci-hub-cli` is missing from PATH or this file changed.
set -euo pipefail
BIN_DIR="${1:-$HOME/orc-bin}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
COMMON_DIR="$(git -C "$SCRIPT_DIR" rev-parse --path-format=absolute --git-common-dir)"
ROOT="$(dirname "$COMMON_DIR")"
TARGET="$ROOT/ci-hub/ci-hub"
OPERATIONAL_TOOL="$HOME/.local/libexec/dev-hermit/operational-tool"
[ -x "$TARGET" ] || { echo "ci-hub not executable at $TARGET" >&2; exit 1; }
[ -x "$OPERATIONAL_TOOL" ] || {
    echo "operational-tool not executable at $OPERATIONAL_TOOL" >&2
    exit 1
}
mkdir -p "$BIN_DIR"
# Write beside the destination and rename, so a pane that execs the shim
# mid-install sees the old file or the new one, never a truncated one.
TMP="$(mktemp "$BIN_DIR/.ci-hub-cli.XXXXXX")"
trap 'rm -f -- "$TMP"' EXIT
cat > "$TMP" <<SHIM
#!/bin/bash
# Generated by scripts/install-ci-hub-shim.sh -- do not edit by hand.
if [[ "\${1:-}" == validate-run ]]; then
    shift
    exec "$OPERATIONAL_TOOL" --run-current-tool --state-root "$ROOT" \\
        --tool-relative ci-hub/ci-hub -- validate-run --state-root "$ROOT" "\$@"
fi
exec "$TARGET" "\$@"
SHIM
chmod 0755 "$TMP"
mv -f -- "$TMP" "$BIN_DIR/ci-hub-cli"
trap - EXIT
echo "installed: $BIN_DIR/ci-hub-cli -> $TARGET (validate-run -> $OPERATIONAL_TOOL --run-current-tool)"
