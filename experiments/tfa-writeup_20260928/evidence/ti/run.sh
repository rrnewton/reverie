#!/bin/bash
# read-only TestInfra failure-text queries, one per test id, bounded
ids="281475243051108 281475243043222 562950242844554 562950211052906 562950361061616 281475244092464 844425197050049 281475271465112 844425263427177 562950216898741 281475240048871 562950220120091 281475243259972 281475243249473 844425202171362 844425205465381 562950274089363 562950215341224 281475238796418 562950215319283 562950212033102 281475235281183 281475235299286 562950213120998 281475236296488 281475250915202 844425193659677 562950354325343 281475240064369"
run_one() {
  id=$1
  timeout 170 meta testinfra.result history --test=$id --statuses=FAILED,FATAL,TIMEOUT --since=ONE_WEEK --limit=3 --output=json > /tmp/sub-tfa2-030/ti/$id.json 2>&1
  echo "$id rc=$?" >> /tmp/sub-tfa2-030/ti/rc.txt
}
: > /tmp/sub-tfa2-030/ti/rc.txt
n=0
for id in $ids; do
  run_one $id &
  n=$((n+1))
  if [ $((n % 6)) -eq 0 ]; then wait; fi
done
wait
echo done
