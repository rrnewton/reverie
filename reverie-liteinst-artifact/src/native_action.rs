fn check_inventory_with_external(
    bytes: &[u8],
    files: &BTreeMap<String, FileIdentity>,
    controls: &BTreeMap<String, FileIdentity>,
    cwd: &Path,
    retained_paths: Option<&BTreeMap<String, PathBuf>>,
    current_paths: Option<&BTreeMap<String, PathBuf>>,
    external: &BTreeMap<String, ExternalLinkWitness>,
) -> Result<CheckedInventory> {
    let inventory = super::native_executor_inputs::parse_executor_inventory(bytes)?;
    let all: BTreeMap<_, _> = files.iter().chain(controls.iter()).collect();
    require(
        all.len() == files.len() + controls.len(),
        "native input collides with control identity",
    )?;
    let mut paths = BTreeMap::new();
    let mut fresh = BTreeMap::new();
    let mut alias_targets = BTreeMap::new();
    let mut representations = BTreeMap::new();
    require(
        external.keys().all(|id| files.contains_key(id)),
        "external input is outside the complete current logical file set",
    )?;
    for witness in external.values() {
        external_witness_shape(witness)?;
    }
    if let Some(current) = current_paths {
        require(
            current.keys().eq(files.keys()),
            "current executor logical member set differs",
        )?;
    }
    if let Some(original) = retained_paths {
        require(
            original.keys().eq(all.keys().copied()),
            "retained executor logical member set differs",
        )?;
    }
    for (id, file) in all {
        let path = if let Some(original) = retained_paths {
            original[id].clone()
        } else if let Some(witness) = external.get(id) {
            witness.requested.clone()
        } else {
            let current_path = current_paths
                .and_then(|paths| paths.get(id))
                .unwrap_or(&file.path);
            current_path
                .strip_prefix(cwd)
                .map_err(|_| {
                    format!(
                        "regular input is outside the actual action project root: {}",
                        current_path.display()
                    )
                })?
                .to_owned()
        };
        let metadata = fs::metadata(&file.path).map_err(|e| e.to_string())?;
        require(
            metadata.is_file(),
            "executor input is not a current regular file",
        )?;
        let observation = (metadata.len(), file.sha256.clone());
        let is_external = external.contains_key(id);
        if let Some(previous) = representations.insert(path.clone(), is_external) {
            require(
                previous == is_external,
                "one input path has conflicting executor representations",
            )?;
        }
        if let Some(witness) = external.get(id) {
            require(
                witness.requested.as_os_str() == path.as_os_str()
                    && !inventory.entries.contains_key(&path),
                "external input conflicts with an executor File row or original spelling",
            )?;
        } else if let Some(previous) = fresh.insert(path.clone(), observation.clone()) {
            require(
                previous == observation,
                "executor row maps to different fresh input contents",
            )?;
        }
        if let Some(previous) = alias_targets.insert(path.clone(), file.path.clone()) {
            require(
                previous == file.path,
                "one original regular Artifact has inconsistent current mappings",
            )?;
        }
        paths.insert(id.clone(), path);
    }
    super::native_executor_inputs::match_regular_files(&inventory, &fresh).map_err(|error| {
        let executor_only = inventory.entries.keys().find(|path| !fresh.contains_key(*path));
        let fresh_only = fresh.keys().find(|path| !inventory.entries.contains_key(*path));
        format!(
            "{error}; executor rows={}, fresh rows={}; first executor-only path: {executor_only:?}; first fresh-only path: {fresh_only:?}",
            inventory.entries.len(),
            fresh.len(),
        )
    })?;
    Ok(CheckedInventory {
        paths,
        control_sha256: controls
            .iter()
            .map(|(id, file)| (id.clone(), file.sha256.clone()))
            .collect(),
    })
}

fn executable_inputs(
    expected: &ExpectedProducer,
    original: &BTreeMap<String, Vec<u8>>,
    files: &BTreeMap<String, FileIdentity>,
) -> Result<()> {
    use std::os::unix::fs::PermissionsExt;
    for command in [&expected.wrapper_argv, &expected.compiler_argv] {
        let first = command.first().ok_or("native tool invocation is empty")?;
        let executable = argument(first, original)?;
        direct_tool_spelling(&executable)?;
        let mut matched = false;
        for (id, spec) in &expected.files {
            if spec.produced.is_some() {
                continue;
            }
            if let Some(members) = &spec.directory_members {
                for relative in members.keys() {
                    let mut path = original[id].clone();
                    if !path.ends_with(b"/") {
                        path.push(b'/');
                    }
                    path.extend_from_slice(relative.as_os_str().as_bytes());
                    if path == executable {
                        let file = &files[&member_id(id, relative)?];
                        require(
                            fs::metadata(&file.path)
                                .map_err(|e| e.to_string())?
                                .permissions()
                                .mode()
                                & 0o111
                                != 0,
                            "pinned native tool lacks executable mode",
                        )?;
                        matched = true;
                    }
                }
            } else if original[id] == executable {
                require(
                    fs::metadata(&files[id].path)
                        .map_err(|e| e.to_string())?
                        .permissions()
                        .mode()
                        & 0o111
                        != 0,
                    "pinned native tool lacks executable mode",
                )?;
                matched = true;
            }
        }
        require(
            matched,
            "native executable lacks independently pinned current tool association",
        )?;
    }
    Ok(())
}

// A flat input can also be named by a tool role. Such a second association
// retains its strict requested-leaf contract, regardless of earlier linker
// capture or another logical ID pointing at the same requested spelling.
fn strict_flat_tools(
    expected: &ExpectedProducer,
    declared: &DeclaredProducer,
    original: &BTreeMap<String, Vec<u8>>,
    custody: &mut Custody,
) -> Result<()> {
    for command in [&expected.wrapper_argv, &expected.compiler_argv] {
        let first = command.first().ok_or("native tool invocation is empty")?;
        let executable = argument(first, original)?;
        for (id, spec) in &expected.files {
            if spec.directory_members.is_none() && original.get(id) == Some(&executable) {
                custody.file(&declared.files[id])?;
            }
        }
    }
    if let Some(contract) = &expected.wrapper_environment_contract {
        for tool in [&contract.launcher, &contract.script] {
            if tool.member.is_none() {
                custody.file(
                    declared
                        .files
                        .get(&tool.input)
                        .ok_or("environment tool input absent")?,
                )?;
            }
        }
    }
    Ok(())
}

fn require_static_producer(expected: &ExpectedProducer) -> Result<()> {
    require(
        expected.selection == "staticlib"
            && expected.role == "detcore-liteinst"
            && expected.crate_name == "detcore_liteinst"
            && expected.features
                == [
                    "exec-native-injection",
                    "exec-private-init",
                    "loader-private-runtime",
                ]
            && expected.profile.opt_level == "3"
            && expected.profile.debuginfo == 0
            && expected.profile.debug_assertions
            && expected.profile.overflow_checks
            && !expected.profile.test,
        "private-static producer requires the exact staticlib cohort",
    )
}

fn require_static_target(actual: &[Vec<u8>]) -> Result<()> {
    let mut targets = Vec::new();
    let mut arguments = actual.iter().skip(1);
    while let Some(argument) = arguments.next() {
        if argument == b"--target" {
            targets.push(
                arguments
                    .next()
                    .ok_or("missing private-static target operand")?
                    .as_slice(),
            );
        } else if let Some(value) = argument.strip_prefix(b"--target=") {
            targets.push(value);
        } else if matches!(
            argument.as_slice(),
            b"--crate-name"
                | b"--crate-type"
                | b"--emit"
                | b"--cfg"
                | b"--check-cfg"
                | b"--edition"
                | b"--out-dir"
                | b"--extern"
                | b"--sysroot"
                | b"--error-format"
                | b"--json"
                | b"--color"
                | b"--cap-lints"
                | b"--diagnostic-width"
                | b"--remap-path-scope"
                | b"--remap-path-prefix"
                | b"--allow"
                | b"--warn"
                | b"--deny"
                | b"--forbid"
                | b"--force-warn"
                | b"--codegen"
                | b"--library-path"
                | b"-o"
                | b"-L"
                | b"-C"
                | b"-Z"
                | b"-A"
                | b"-W"
                | b"-D"
                | b"-F"
        ) {
            // A remap or another option's operand spelling --target=... is
            // data, not the selected compiler target.
            arguments
                .next()
                .ok_or("missing private-static compiler option operand")?;
        } else if argument.starts_with(b"-") {
            require(
                argument.contains(&b'=')
                    || [b"-C", b"-Z", b"-L", b"-A", b"-W", b"-D", b"-F"]
                        .iter()
                        .any(|prefix| argument.starts_with(*prefix) && argument.len() > 2)
                    || matches!(argument.as_slice(), b"-v" | b"-vv" | b"--verbose"),
                "unsupported private-static compiler option arity",
            )?;
        }
    }
    require(
        targets == [b"x86_64-unknown-linux-musl".as_slice()],
        "private-static compiler target differs from the selected musl target",
    )
}

fn profile_arguments(expected: &ExpectedProducer, actual: &[Vec<u8>]) -> Result<()> {
    if expected.selection == "staticlib" {
        require_static_producer(expected)?;
        require_static_target(actual)?;
    }
    let values: Vec<_> = actual
        .iter()
        .map(|arg| {
            std::str::from_utf8(arg).map_err(|_| {
                "non-UTF8 Rust option requires an explicit supported recipe".to_owned()
            })
        })
        .collect::<Result<_>>()?;
    let mut flags: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut profile_flags = BTreeMap::new();
    let mut features = BTreeSet::new();
    let mut index = 1;
    while index < values.len() {
        let value = values[index];
        let (key, val) = if matches!(
            value,
            "--crate-name" | "--crate-type" | "--emit" | "--cfg" | "-C" | "--codegen"
        ) {
            index += 1;
            (
                value,
                *values.get(index).ok_or("missing Rust option operand")?,
            )
        } else if let Some(val) = value.strip_prefix("-C") {
            ("-C", val)
        } else if let Some((key, val)) = value.split_once('=') {
            (key, val)
        } else {
            (value, "")
        };
        let key = if key == "--codegen" { "-C" } else { key };
        require(
            key != "--test" && key != "--print" && key != "--version" && !value.starts_with('@'),
            "native producer uses non-codegen/test or unresolved nested response arguments",
        )?;
        require(
            !value.starts_with("-O") && !value.starts_with("-g"),
            "native profile requires explicit codegen options, not -O/-g aliases",
        )?;
        if key == "--cfg" && val.starts_with("feature=") {
            let feature = val
                .strip_prefix("feature=\"")
                .and_then(|v| v.strip_suffix('"'))
                .ok_or("malformed compiler feature configuration")?;
            require(
                features.insert(feature.to_owned()),
                "duplicate compiler feature",
            )?;
        }
        if key == "-C" {
            let (name, setting) = match val.split_once('=') {
                Some((name, setting)) => (name, Some(setting)),
                None => (val, None),
            };
            require(!name.is_empty(), "codegen option has no name")?;
            let normalized = match name {
                "opt-level" => Some(match setting {
                    Some(value @ ("0" | "1" | "2" | "3" | "s" | "z")) => value,
                    _ => return Err("unsupported explicit native opt-level".into()),
                }),
                "debuginfo" => Some(match setting {
                    Some("0" | "none") => "0",
                    Some("1" | "limited") => "1",
                    Some("2" | "full") => "2",
                    Some(value @ ("line-tables-only" | "line-directives-only")) => value,
                    _ => return Err("unsupported explicit native debuginfo".into()),
                }),
                "debug-assertions" | "overflow-checks" => Some(match setting {
                    None | Some("y" | "yes" | "on" | "true") => "yes",
                    Some("n" | "no" | "off" | "false") => "no",
                    _ => return Err(format!("unsupported explicit native {name}")),
                }),
                "opt_level" | "debug_assertions" | "overflow_checks" => {
                    return Err("unsupported native profile option spelling".into());
                }
                "force-unwind-tables" => {
                    // rustc's boolean grammar treats an omitted value as true.
                    // This is not a profile default: invocation_join still binds
                    // every raw argument, including the exact option spelling.
                    require(
                        matches!(
                            setting,
                            None | Some("y" | "yes" | "on" | "true" | "n" | "no" | "off" | "false")
                        ),
                        "unsupported explicit native force-unwind-tables",
                    )?;
                    None
                }
                _ => {
                    require(setting.is_some(), "codegen option lacks explicit value")?;
                    None
                }
            };
            if let Some(setting) = normalized {
                // The complete argv is independently bound by invocation_join.
                // Validate every occurrence; only valid earlier defaults may be
                // superseded by the last explicit rustc codegen setting.
                profile_flags.insert(name, setting);
            }
            flags
                .entry(format!("-C{name}"))
                .or_default()
                .push(setting.unwrap_or("").to_owned());
        } else {
            flags
                .entry(key.to_owned())
                .or_default()
                .push(val.to_owned());
        }
        index += 1;
    }
    let exact = |key: &str, value: &str| -> Result<()> {
        require(
            flags.get(key).is_some_and(|v| v == &[value]),
            format!("native compiler {key} differs from selected cohort"),
        )
    };
    let effective = |key: &str, value: &str| -> Result<()> {
        require(
            profile_flags.get(key) == Some(&value),
            format!("native compiler -C{key} differs from selected cohort"),
        )
    };
    exact("--crate-name", &expected.crate_name)?;
    exact(
        "--crate-type",
        match expected.selection.as_str() {
            "cdylib" => "cdylib",
            "staticlib" => "staticlib",
            "code-rlib-static_pic" => "rlib",
            _ => return Err("unsupported selected native compiler product".into()),
        },
    )?;
    effective("opt-level", &expected.profile.opt_level)?;
    effective("debuginfo", &expected.profile.debuginfo.to_string())?;
    effective(
        "debug-assertions",
        if expected.profile.debug_assertions {
            "yes"
        } else {
            "no"
        },
    )?;
    effective(
        "overflow-checks",
        if expected.profile.overflow_checks {
            "yes"
        } else {
            "no"
        },
    )?;
    require(
        !expected.profile.test
            && features == expected.features.iter().cloned().collect()
            && features.len() == expected.features.len(),
        "native compiler feature/test cohort differs",
    )?;
    require(
        flags
            .get("--emit")
            .is_some_and(|v| v.len() == 1 && v[0].starts_with("link=") && !v[0].contains(',')),
        "native compiler does not emit one real code product",
    )?;
    Ok(())
}
fn invocation_join(
    expected: &ExpectedProducer,
    paths: &BTreeMap<String, Vec<u8>>,
    observation: &InvocationObservation,
    context: &ContextObservation,
) -> Result<()> {
    require(
        observation.expanded_argv == arguments(&expected.compiler_argv, paths)?
            && observation.cwd == argument(&expected.cwd, paths)?,
        "normalized native compiler recipe/cwd differs",
    )?;
    let env: BTreeMap<Vec<u8>, Vec<u8>> =
        environment_arguments(&expected.compiler_environment, paths, context)?
            .into_iter()
            .map(|(key, value)| (key.into_bytes(), value))
            .collect();
    require(
        observation.env.iter().cloned().collect::<BTreeMap<_, _>>() == env,
        "normalized native compiler environment differs",
    )?;
    // The normalized compiler itself must be a pinned current file, including
    // the explicit member of a declared toolchain directory Artifact.
    let mut compiler_bound = false;
    for (id, file) in &expected.files {
        if file.produced.is_some() {
            continue;
        }
        if let Some(members) = &file.directory_members {
            for relative in members.keys() {
                let mut original = paths[id].clone();
                if !original.ends_with(b"/") {
                    original.push(b'/');
                }
                original.extend_from_slice(relative.as_os_str().as_bytes());
                compiler_bound |= observation.expanded_argv.first() == Some(&original);
            }
        } else {
            compiler_bound |= observation.expanded_argv.first() == Some(&paths[id]);
        }
    }
    require(
        compiler_bound,
        "normalized compiler executable is not an independently pinned input",
    )?;
    profile_arguments(expected, &observation.expanded_argv)?;
    let emit = [b"--emit=link=".as_slice(), paths["$product"].as_slice()].concat();
    let pair = [b"link=".as_slice(), paths["$product"].as_slice()].concat();
    require(
        observation.expanded_argv.iter().any(|arg| arg == &emit)
            || observation
                .expanded_argv
                .windows(2)
                .any(|args| args[0] == b"--emit" && args[1] == pair),
        "normalized native emit does not name the declared product",
    )
}

struct CheckedProducer {
    files: BTreeMap<String, FileIdentity>,
    product: FileIdentity,
    evidence: FileIdentity,
    paths: BTreeMap<String, Vec<u8>>,
    invocation: InvocationObservation,
}
fn retained(
    expected: &ExpectedProducer,
    expected_dependencies: &BTreeMap<String, ExpectedProducer>,
    declared: &DeclaredProducer,
    graph: &DeclaredGraph,
    custody: &mut Custody,
) -> Result<CheckedProducer> {
    let InputFiles {
        files,
        inventory_paths,
    } = open_inputs(expected, declared, graph, custody)?;
    custody.directory(&declared.directory)?;
    let recipe_bytes = custody.bytes(&declared.recipe)?;
    let evidence_bytes = custody.bytes(&declared.evidence)?;
    let record = decode_retained(&evidence_bytes)?;
    let controls = open_retained_controls(expected, expected_dependencies, declared, custody)?;
    let original_inputs: BTreeMap<_, _> =
        super::native_action_input::original_input_paths(&recipe_bytes)?
            .into_iter()
            .map(|(id, path)| (id, path.as_os_str().as_bytes().to_vec()))
            .collect();
    require(
        record.original_inputs == original_inputs,
        "retained native original inputs differ from its guarded normal recipe",
    )?;
    let paths = retained_paths(&record, declared)?;
    // An originally external input may relocate, but it cannot become an alias
    // of a current selected output. Open those strict files before comparing
    // canonical identities; the full custody transaction keeps them through close.
    let mut output_paths = BTreeSet::new();
    if !expected.external_linked_inputs.is_empty() {
        output_paths.extend(external_dependency_outputs(graph, custody)?);
        for path in [
            &declared.product,
            &declared.recipe,
            &declared.invocation,
            &declared.evidence,
            &declared.finalization,
            &declared.input_inventory,
        ]
        .into_iter()
        .chain(declared.qualified_product.iter())
        .chain(declared.metadata_full.iter())
        {
            output_paths.insert(custody.file(path)?.path);
        }
    }
    external_link_eligibility(
        expected,
        declared,
        graph,
        &files,
        &paths,
        &controls,
        &output_paths,
    )?;
    let external = retained_external_links(expected, &record)?;
    let inventory_bytes = custody.bytes(&declared.input_inventory)?;
    let inventory = check_inventory_with_external(
        &inventory_bytes,
        &files,
        &controls,
        Path::new("/"),
        Some(&record.inventory_paths),
        Some(&inventory_paths),
        &external,
    )?;
    let final_bytes = custody.bytes(&declared.finalization)?;
    let finalization: Finalization = decode(&final_bytes)?;
    let invocation_bytes = custody.bytes(&declared.invocation)?;
    let invocation = parse_invocation_handoff(&invocation_bytes)?;
    executable_inputs(expected, &paths, &files)?;
    strict_flat_tools(expected, declared, &paths, custody)?;
    environment_contract(expected, &paths, &files)?;
    context_environment(&record.context, &record.wrapper_environment)?;
    invocation_join(expected, &paths, &invocation, &record.context)?;
    let product = custody.file(&declared.product)?;
    if let Some(path) = &declared.qualified_product {
        require(
            custody.file(path)?.sha256 == product.sha256,
            "retained qualified copy differs from actual product",
        )?;
    }
    require(
        record.role == expected.role
            && record.producer == expected.producer
            && record.configuration == expected.configuration
            && record.selection == expected.selection
            && record.wrapper_status == 0
            && record.wrapper_argv == arguments(&expected.wrapper_argv, &paths)?
            && record.wrapper_cwd == argument(&expected.cwd, &paths)?
            && record.wrapper_environment
                == environment_arguments(&expected.wrapper_environment, &paths, &record.context)?
            && record.input_sha256
                == files
                    .iter()
                    .map(|(id, file)| (id.clone(), file.sha256.clone()))
                    .collect()
            && record.dependencies == expected.dependencies
            && record.metadata_dependencies == expected.metadata_dependencies
            && record.input_inventory_sha256 == sha256(&inventory_bytes)
            && record.control_sha256 == inventory.control_sha256
            && record.recipe_sha256 == sha256(&recipe_bytes)
            && record.invocation_sha256 == sha256(&invocation_bytes)
            && record.product_sha256 == product.sha256
            && finalization.kind == "reverie-native-closed/v1"
            && finalization.evidence_sha256 == sha256(&evidence_bytes)
            && finalization.product_sha256 == product.sha256,
        "retained native producer/recipe/input/product/finalization association differs",
    )?;
    Ok(CheckedProducer {
        files,
        product,
        evidence: FileIdentity::read(&declared.evidence)?,
        paths,
        invocation,
    })
}

fn decode<T: serde::de::DeserializeOwned>(bytes: &[u8]) -> Result<T> {
    serde_json::from_value(super::native_wire::parse(
        bytes,
        super::native_results::MAX_REPORT_BYTES,
    )?)
    .map_err(|e| format!("native action record: {e}"))
}
fn graph_shape(expected: &ExpectedGraph, declared: &DeclaredGraph) -> Result<()> {
    require(
        expected
            .dependencies
            .keys()
            .eq(declared.dependencies.keys()),
        "declared producer role set differs from independent graph",
    )?;
    require(
        !expected.dependencies.contains_key(&expected.leaf.role),
        "leaf aliases a dependency role",
    )?;
    for (role, producer) in &expected.dependencies {
        require(
            role == &producer.role && declared.dependencies[role].role == *role,
            "declared dependency role key differs",
        )?;
    }
    Ok(())
}
fn check_recipes(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    custody: &mut Custody,
    retained_leaf: bool,
) -> Result<Vec<u8>> {
    graph_shape(expected, declared)?;
    let bytes = custody.bytes(&declared.leaf.recipe)?;
    // Current typed edges supply these paths. A retained recipe's original
    // paths are never used for filesystem discovery after relocation.
    let mut dependency_recipes = BTreeMap::new();
    for producer in declared.dependencies.values() {
        let bytes = custody.bytes(&producer.recipe)?;
        if let Some(prior) = dependency_recipes.insert(producer.recipe.clone(), bytes.clone()) {
            require(prior == bytes, "declared recipe changed during acquisition")?;
        }
    }
    if retained_leaf {
        super::native_action_input::validate_retained_declared_graph(
            &bytes,
            expected,
            declared,
            &dependency_recipes,
        )?;
    } else {
        let outputs = super::native_action_input::LeafOutputs {
            recipe: declared.leaf.recipe.clone(),
            product: declared.leaf.product.clone(),
            directory: declared.leaf.directory.clone(),
            input_inventory: declared.leaf.input_inventory.clone(),
            invocation: declared.leaf.invocation.clone(),
            evidence: declared.leaf.evidence.clone(),
            finalization: declared.leaf.finalization.clone(),
            qualified_product: declared.leaf.qualified_product.clone(),
        };
        let observed = super::native_action_input::parse_declared_graph(
            &bytes,
            expected,
            &outputs,
            &dependency_recipes,
        )?;
        require(
            observed == *declared,
            "declared graph differs from guarded normal recipe and consumed code product associations",
        )?;
    }
    Ok(bytes)
}

// A retained dependency was produced with its own transitive expectation map.
// Project that exact map from the caller's independent typed graph, never from
// the retained manifest, recipe, or observed product.
fn expected_dependency_closure(
    producer: &ExpectedProducer,
    available: &BTreeMap<String, ExpectedProducer>,
) -> Result<BTreeMap<String, ExpectedProducer>> {
    let mut pending: Vec<_> = producer
        .dependencies
        .values()
        .chain(producer.metadata_dependencies.values())
        .cloned()
        .collect();
    let mut result = BTreeMap::new();
    while let Some(role) = pending.pop() {
        require(
            role != producer.role,
            "independent expected dependency graph contains a cycle",
        )?;
        if result.contains_key(&role) {
            continue;
        }
        let dependency = available
            .get(&role)
            .ok_or("independent expected dependency role is absent")?;
        require(
            dependency.role == role,
            "independent expected dependency role key differs",
        )?;
        pending.extend(
            dependency
                .dependencies
                .values()
                .chain(dependency.metadata_dependencies.values())
                .cloned(),
        );
        result.insert(role, dependency.clone());
    }
    Ok(result)
}

fn dependencies(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    custody: &mut Custody,
) -> Result<BTreeMap<String, CheckedProducer>> {
    graph_shape(expected, declared)?;
    let mut result = BTreeMap::new();
    for (role, producer) in &expected.dependencies {
        require(
            producer.selection == "code-rlib-static_pic",
            "guest dependency is not a code rlib producer",
        )?;
        result.insert(
            role.clone(),
            retained(
                producer,
                &expected_dependency_closure(producer, &expected.dependencies)?,
                &declared.dependencies[role],
                declared,
                custody,
            )?,
        );
    }
    for (role, producer) in &expected.dependencies {
        join_consumed(
            producer,
            &declared.dependencies[role],
            &result[role].files,
            declared,
            &result,
        )?;
    }
    Ok(result)
}
// A typed graph can enter the factory without passing through the JSON
// adapter. Require the actual direct-or-inherited code association again before
// a source context can be built; metadata or a hidden code file cannot stand in
// for either normal stable or advanced-linking product consumption.
pub(super) fn declared_link_coverage(
    expected: &ExpectedProducer,
    action: &DeclaredProducer,
    graph: &DeclaredGraph,
) -> Result<()> {
    require(
        matches!(action.selection.as_str(), "cdylib" | "staticlib")
            || action.linked_inputs.is_empty(),
        "nonlink code rlib has inherited linker inputs",
    )?;
    for role in action
        .dependencies
        .values()
        .chain(action.metadata_dependencies.values())
        .collect::<BTreeSet<_>>()
    {
        let producer = graph
            .dependencies
            .get(role)
            .ok_or("selected role lacks its configured producer")?;
        require(
            action.consumed_inputs.values().any(|path| {
                *path == producer.product || producer.metadata_full.as_ref() == Some(path)
            }),
            "selected producer has no direct compiler code or metadata input",
        )?;
    }
    for (id, role) in &action.metadata_dependencies {
        if let Some(code_role) = action.dependencies.get(id) {
            require(
                code_role == role,
                "one selected input claims different code and metadata roles",
            )?;
        }
    }
    for (id, current) in &action.linked_inputs {
        let pin = expected
            .files
            .get(id)
            .ok_or("linked input lacks an independent expectation")?;
        require(
            action.files.get(id) == Some(current)
                && action
                    .consumed_inputs
                    .get(id)
                    .is_none_or(|direct| direct == current),
            "linked input loses its exact current file or conflicts with a direct input",
        )?;
        let roles: Vec<_> = graph
            .dependencies
            .iter()
            .filter(|(_, producer)| producer.product == *current)
            .map(|(role, _)| role)
            .collect();
        require(
            roles.len() <= 1,
            "linked product claims different configured producer roles",
        )?;
        if let Some(role) = roles.first() {
            require(
                expected.dependencies.get(id) == Some(*role)
                    && action.dependencies.get(id) == Some(*role),
                "linked code product lacks its exact independent configured role",
            )?;
        } else {
            require(
                pin.produced.is_none()
                    && pin.directory_members.is_none()
                    && pin.source_key.is_none()
                    && pin.compiler_filename.is_none()
                    && pin.sha256.len() == 64
                    && pin
                        .sha256
                        .bytes()
                        .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)),
                "unqualified linked input requires independently pinned regular bytes without source authority",
            )?;
        }
    }
    if matches!(action.selection.as_str(), "cdylib" | "staticlib") {
        for (role, producer) in &graph.dependencies {
            require(
                producer.selection == "code-rlib-static_pic"
                    && action
                        .consumed_inputs
                        .iter()
                        .chain(action.linked_inputs.iter())
                        .any(|(id, path)| {
                            *path == producer.product
                                && expected.dependencies.get(id) == Some(role)
                                && action.dependencies.get(id) == Some(role)
                        }),
                "ordinary constructor lacks actual compiler/linker code-product coverage of a qualified role",
            )?;
        }
    }
    Ok(())
}

fn join_consumed(
    expected: &ExpectedProducer,
    action: &DeclaredProducer,
    files: &BTreeMap<String, FileIdentity>,
    graph: &DeclaredGraph,
    producers: &BTreeMap<String, CheckedProducer>,
) -> Result<()> {
    declared_link_coverage(expected, action, graph)?;
    for (input, role) in &expected.dependencies {
        let producer = producers
            .get(role)
            .ok_or("required normal declared producer edge absent")?;
        let association = graph
            .dependencies
            .get(role)
            .ok_or("required configured producer association absent")?;
        require(
            action.files[input] == association.product
                && (action.consumed_inputs.get(input) == Some(&association.product)
                    || action.linked_inputs.get(input) == Some(&association.product))
                && files.get(input) == Some(&producer.product),
            "consumed code product is not the exact declared configured producer output",
        )?;
    }
    for (input, role) in &expected.metadata_dependencies {
        let association = graph
            .dependencies
            .get(role)
            .ok_or("required declared metadata producer edge absent")?;
        require(
            producers.contains_key(role),
            "metadata companion lacks its selected code producer",
        )?;
        let path = association
            .metadata_full
            .as_ref()
            .ok_or("normal metadata companion association absent")?;
        require(
            action.files.get(input) == Some(path)
                && action.consumed_inputs.get(input) == Some(path)
                && files.contains_key(input),
            "consumed metadata does not match the exact normal typed companion",
        )?;
    }
    Ok(())
}
fn constructor_code_coverage(expected: &ExpectedGraph) -> Result<()> {
    if matches!(expected.leaf.selection.as_str(), "cdylib" | "staticlib") {
        require(
            expected.leaf.dependencies.values().collect::<BTreeSet<_>>()
                == expected.dependencies.keys().collect::<BTreeSet<_>>(),
            "ordinary constructor requires actual leaf code-product coverage of every qualified dependency role",
        )?;
    }
    Ok(())
}

fn source_binding(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    files: &BTreeMap<String, FileIdentity>,
    producers: &BTreeMap<String, CheckedProducer>,
    artifact: &FileIdentity,
    leaf_paths: &BTreeMap<String, Vec<u8>>,
    leaf_invocation: &InvocationObservation,
) -> Result<NativeSourceBinding> {
    constructor_code_coverage(expected)?;
    declared_link_coverage(&expected.leaf, &declared.leaf, declared)?;
    let mut binding = NativeSourceBinding {
        files: BTreeMap::new(),
        compiler_filenames: BTreeMap::new(),
        packages: BTreeMap::new(),
        artifact: artifact.clone(),
    };
    for (want, action, current, paths, invocation) in std::iter::once((
        &expected.leaf,
        &declared.leaf,
        files,
        leaf_paths,
        leaf_invocation,
    ))
    .chain(expected.dependencies.iter().map(|(role, want)| {
        (
            want,
            &declared.dependencies[role],
            &producers[role].files,
            &producers[role].paths,
            &producers[role].invocation,
        )
    })) {
        let package = NativePackage {
            crate_name: want.crate_name.clone(),
            features: want.features.clone(),
            profile: NativeProfile {
                opt_level: want.profile.opt_level.clone(),
                debuginfo: want.profile.debuginfo,
                debug_assertions: want.profile.debug_assertions,
                overflow_checks: want.profile.overflow_checks,
                test: want.profile.test,
            },
        };
        require(
            binding
                .packages
                .insert(want.role.clone(), package)
                .is_none(),
            "duplicate native source package role",
        )?;
        for (id, file) in file_specs(want)? {
            if let Some(role) = &file.source_key {
                let identity = current[&id].clone();
                if let Some(prior) = binding.files.insert(role.clone(), identity.clone()) {
                    require(
                        prior == identity,
                        "native source role has conflicting current materializations",
                    )?;
                }
                if let Some(filename) = &file.compiler_filename {
                    let filename = argument(filename, paths)?;
                    let mut checked = false;
                    // Bind the catalog file to a complete declared source-tree
                    // member by its fresh identity, not its basename. Derive
                    // only its original compiler spelling through the explicit
                    // logical mapping retained for this producer.
                    for (tree_id, tree_spec) in &want.files {
                        if action.files[tree_id] != action.source_tree {
                            continue;
                        }
                        require(
                            action
                                .input_roots
                                .values()
                                .any(|path| *path == action.source_tree),
                            "source tree is not an actual compiler input",
                        )?;
                        let members = tree_spec
                            .directory_members
                            .as_ref()
                            .ok_or("compiler source tree lacks complete directory expectation")?;
                        for relative in members.keys() {
                            let member = member_id(tree_id, relative)?;
                            if current.get(&member) == Some(&identity) {
                                super::native_source::checked_compiler_filename(
                                    &paths[tree_id],
                                    relative,
                                    &invocation.expanded_argv,
                                    &filename,
                                )?;
                                checked = true;
                            }
                        }
                    }
                    require(
                        checked,
                        "compiled source role is absent from the actual complete source tree",
                    )?;
                    if let Some(prior) = binding
                        .compiler_filenames
                        .insert(role.clone(), filename.clone())
                    {
                        require(
                            prior == filename,
                            "native source role has conflicting compiler spellings",
                        )?;
                    }
                }
            } else {
                require(
                    file.compiler_filename.is_none(),
                    "compiler filename lacks a source role",
                )?;
            }
        }
    }
    Ok(binding)
}

fn capture_commands(custody: &mut Custody, runner: &Runner, from: usize) -> Result<()> {
    let mut errors = Vec::new();
    for command in &runner.commands[from..] {
        for stream in [&command.stdout, &command.stderr] {
            if let Err(error) = custody.file(&stream.path) {
                errors.push(error);
            }
        }
    }
    require(errors.is_empty(), errors.join("; "))
}
enum PhysicalQualification {
    Ordinary(NativeConstructorQualification),
    Standalone(NativeStandaloneConstructorQualification),
    Entry(NativeEntryQualification),
}
impl PhysicalQualification {
    fn into_owned(self, compilation: Compilation) -> OwnedProduct {
        match self {
            Self::Ordinary(qualification) => {
                OwnedProduct::Constructor(Box::new(QualifiedConstructor {
                    compilation,
                    qualification,
                }))
            }
            Self::Standalone(qualification) => {
                OwnedProduct::StandaloneConstructor(Box::new(QualifiedStandaloneConstructor {
                    compilation,
                    qualification,
                }))
            }
            Self::Entry(qualification) => {
                OwnedProduct::NativeEntry(Box::new(QualifiedNativeEntry {
                    compilation,
                    qualification,
                }))
            }
        }
    }
}
fn qualify_physical(
    product: &FileIdentity,
    runner: &mut Runner,
    sources: &VerifiedNativeSources,
    custody: &mut Custody,
) -> Result<PhysicalQualification> {
    let before = runner.commands.len();
    let primary = match sources.cohort() {
        super::NoScopeCohort::DetcoreOrdinary101 => {
            super::native_source::qualify_native_constructor(&product.path, runner, sources)
                .map(PhysicalQualification::Ordinary)
        }
        super::NoScopeCohort::StandaloneRelease62 => {
            super::native_source::qualify_native_standalone_constructor(
                &product.path,
                runner,
                sources,
            )
            .map(PhysicalQualification::Standalone)
        }
        super::NoScopeCohort::DetcoreNative101 => {
            super::native_source::qualify_native_entry(&product.path, runner, sources)
                .map(PhysicalQualification::Entry)
        }
    };
    finish(primary, capture_commands(custody, runner, before))
}

fn finish_declared_qualification<T>(
    primary: Result<T>,
    source_close: Result<()>,
    custody: &Custody,
) -> Result<T> {
    finish(finish(primary, source_close), custody.close())
}

fn with_declared_qualification<T>(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    runner: &mut Runner,
    cohort: super::NoScopeCohort,
    consume: impl FnOnce(
        Compilation,
        PhysicalQualification,
        &VerifiedNativeSources,
        &Custody,
    ) -> Result<T>,
) -> Result<T> {
    let mut custody = Custody::new();
    let mut source_close = Ok(());
    let primary = (|| {
        require(
            expected.leaf.selection == "cdylib",
            "native physical factory requires selected cdylib",
        )?;
        check_recipes(expected, declared, &mut custody, true)?;
        let producers = dependencies(expected, declared, &mut custody)?;
        let leaf = retained(
            &expected.leaf,
            &expected.dependencies,
            &declared.leaf,
            declared,
            &mut custody,
        )?;
        join_consumed(
            &expected.leaf,
            &declared.leaf,
            &leaf.files,
            declared,
            &producers,
        )?;
        let binding = source_binding(
            expected,
            declared,
            &leaf.files,
            &producers,
            &leaf.product,
            &leaf.paths,
            &leaf.invocation,
        )?;
        let sources = VerifiedNativeSources::from_checked_action(&binding)?;
        let qualified = (|| {
            require(
                sources.cohort() == cohort,
                "native source cohort does not match the requested admission path",
            )?;
            let qualification = qualify_physical(&leaf.product, runner, &sources, &mut custody)?;
            let compilation = Compilation {
                product: leaf.product,
                evidence: leaf.evidence,
                reused: true,
            };
            consume(compilation, qualification, &sources, &custody)
        })();
        // Evaluate the consumer before the final source check, including when
        // it fails. The outer close also covers failures before source admission.
        source_close = sources.verify_unchanged();
        qualified
    })();
    finish_declared_qualification(primary, source_close, &custody)
}

/// Fresh downstream rebinding of a normal declared ordinary constructor.
/// Cache reuse retains historical attribution and rechecks every current input.
/// Other cohorts, records alone and private-static archives cannot enter here.
pub fn qualify_declared_constructor(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    runner: &mut Runner,
) -> Result<QualifiedConstructor> {
    with_declared_qualification(
        expected,
        declared,
        runner,
        super::NoScopeCohort::DetcoreOrdinary101,
        |compilation, qualification, _, _| match qualification {
            PhysicalQualification::Ordinary(qualification) => Ok(QualifiedConstructor {
                compilation,
                qualification,
            }),
            _ => Err("ordinary constructor received another physical admission".into()),
        },
    )
}

/// Fresh standalone constructor admission with the existing complete standalone
/// cohort, source and physical predicates. This is distinct from explicit entry.
pub fn qualify_declared_standalone_constructor(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    runner: &mut Runner,
) -> Result<QualifiedStandaloneConstructor> {
    with_declared_qualification(
        expected,
        declared,
        runner,
        super::NoScopeCohort::StandaloneRelease62,
        |compilation, qualification, _, _| match qualification {
            PhysicalQualification::Standalone(qualification) => {
                Ok(QualifiedStandaloneConstructor {
                    compilation,
                    qualification,
                })
            }
            _ => Err("standalone constructor received another physical admission".into()),
        },
    )
}

/// Admit the declared explicit-entry cdylib and retain its private source/input
/// custody through the consumer's loader/bootstrap/runtime checks. The callback
/// must return failures as Result. No publication guard may be completed until
/// this function returns Ok; callback and final-close failures are both retained.
/// This API does not admit a private-static archive or its final ET_EXEC link.
pub fn with_declared_native_entry<T>(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    runner: &mut Runner,
    consume: impl FnOnce(&NativeEntryScope<'_>) -> Result<T>,
) -> Result<T> {
    with_declared_qualification(
        expected,
        declared,
        runner,
        super::NoScopeCohort::DetcoreNative101,
        |compilation, qualification, sources, custody| {
            let PhysicalQualification::Entry(qualification) = qualification else {
                return Err("explicit entry received another physical admission".into());
            };
            consume(&NativeEntryScope {
                qualified: QualifiedNativeEntry {
                    compilation,
                    qualification,
                },
                sources,
                custody,
            })
        },
    )
}

fn private_static_source_joins(
    expected: &ExpectedGraph,
    binding: &NativeSourceBinding,
    leaf: &CheckedProducer,
    producers: &BTreeMap<String, CheckedProducer>,
) -> Result<()> {
    require_static_producer(&expected.leaf)?;
    require_static_target(&leaf.invocation.expanded_argv)?;
    for (role, producer) in &expected.dependencies {
        require(
            producer.crate_name == role.replace('-', "_")
                && producer.profile.opt_level == "3"
                && producer.profile.debuginfo == 0
                && producer.profile.debug_assertions
                && producer.profile.overflow_checks
                && !producer.profile.test,
            "private-static dependency crate/profile differs from the selected cohort",
        )?;
        require_static_target(&producers[role].invocation.expanded_argv)?;
    }
    for &(key, owner, compiled) in super::private_static::native_source_roles() {
        let mut present = false;
        for producer in std::iter::once(&expected.leaf).chain(expected.dependencies.values()) {
            for (_, file) in file_specs(producer)? {
                if file.source_key.as_deref() != Some(key) {
                    continue;
                }
                require(
                    producer.role == owner && producer.crate_name == owner.replace('-', "_"),
                    format!(
                        "private-static source role belongs to a different configured producer: {key}"
                    ),
                )?;
                require(
                    !compiled || file.compiler_filename.is_some(),
                    format!("private-static source role lacks its compiled tree member: {key}"),
                )?;
                present = true;
            }
        }
        require(
            present
                && binding.files.contains_key(key)
                && (!compiled || binding.compiler_filenames.contains_key(key)),
            format!("private-static source role is missing: {key}"),
        )?;
    }
    require(
        ["reverie-inguest", "reverie-liteinst", "reverie-loader"]
            .iter()
            .all(|role| expected.dependencies.contains_key(*role)),
        "private-static graph lacks a required compiled runtime producer",
    )?;
    Ok(())
}

fn private_static_output_separation(declared: &DeclaredGraph, output: &Path) -> Result<()> {
    require(
        output.is_absolute()
            && output.components().all(|part| {
                matches!(
                    part,
                    std::path::Component::RootDir | std::path::Component::Normal(_)
                )
            }),
        "native static output needs an absolute ordinary path",
    )?;
    let parent = output.parent().ok_or("native static output lacks parent")?;
    require(
        fs::canonicalize(parent).map_err(|error| error.to_string())? == parent,
        "native static output parent is not canonical",
    )?;
    for action in std::iter::once(&declared.leaf).chain(declared.dependencies.values()) {
        for input in action
            .files
            .values()
            .chain(action.input_roots.values())
            .chain([&action.directory, &action.product])
        {
            let current = fs::canonicalize(input).map_err(|error| error.to_string())?;
            require(
                !output.starts_with(&current) && !current.starts_with(output),
                "native static link output overlaps a retained producer or input",
            )?;
        }
    }
    Ok(())
}

/// Rebind a normal selected staticlib and its complete declared producer graph.
/// This distinct callback scope preserves source/archive ownership through the
/// actual final link and existing physical inspections. It grants neither DSO
/// constructor/explicit-entry authority nor execution authority for the final
/// ET_EXEC. The output directory belongs to this consumer's declared link action,
/// separately from all retained producer/input directories. Publish only after
/// this function returns success, including its final custody close.
pub fn with_declared_private_static<T>(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    link_output_directory: &Path,
    runner: &mut Runner,
    consume: impl FnOnce(
        &super::private_static::NativeStaticSource<'_>,
        &super::private_static::NativeStaticArchive,
        &mut Runner,
    ) -> Result<T>,
) -> Result<T> {
    let mut custody = Custody::new();
    let primary = (|| {
        require_static_producer(&expected.leaf)?;
        constructor_code_coverage(expected)?;
        check_recipes(expected, declared, &mut custody, true)?;
        let producers = dependencies(expected, declared, &mut custody)?;
        let leaf = retained(
            &expected.leaf,
            &expected.dependencies,
            &declared.leaf,
            declared,
            &mut custody,
        )?;
        join_consumed(
            &expected.leaf,
            &declared.leaf,
            &leaf.files,
            declared,
            &producers,
        )?;
        let binding = source_binding(
            expected,
            declared,
            &leaf.files,
            &producers,
            &leaf.product,
            &leaf.paths,
            &leaf.invocation,
        )?;
        private_static_source_joins(expected, &binding, &leaf, &producers)?;
        private_static_output_separation(declared, link_output_directory)?;
        super::private_static::with_checked_native_static(
            &binding,
            &custody,
            &leaf.evidence,
            link_output_directory,
            runner,
            consume,
        )
    })();
    finish(primary, custody.close())
}

/// Result of one owned whole-wrapper operation. Rlibs carry compilation evidence;
/// staticlibs likewise carry compilation only until their distinct scoped
/// downstream factory. Cdylibs carry their exact cohort's physical evidence.
pub enum OwnedProduct {
    Compilation(Compilation),
    Constructor(Box<QualifiedConstructor>),
    StandaloneConstructor(Box<QualifiedStandaloneConstructor>),
    NativeEntry(Box<QualifiedNativeEntry>),
}

fn write_new(path: &Path, bytes: &[u8], custody: &mut Custody) -> Result<FileIdentity> {
    super::write_new(path, bytes)?;
    let file = custody.file(path)?;
    require(
        file.sha256 == sha256(bytes),
        "native declared output differs after write",
    )?;
    Ok(file)
}
/// Own one unchanged normal rustc_action and withhold successful finalization
/// until qualification, copying and every input/output close have succeeded.
/// The concrete Runner owns execution bounds and process-group cleanup. No
/// user callback runs with authority. Panics/abort retain Runner's documented
/// enclosing-cgroup cleanup requirement.
pub fn with_owned_rust_action(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    request: &WrapperRequest,
    runner: &mut Runner,
) -> Result<OwnedProduct> {
    let context = ExecutionContext::capture()?;
    run_owned_rust_action(
        expected,
        declared,
        request,
        runner,
        &mut Custody::new(),
        &context,
    )
}

/// Guard the independent expected manifest and the exact normal input recipe
/// for the full owned transaction. Parsing these bytes alone grants no source
/// authority; every declared producer and the leaf still passes the factory.
pub fn with_owned_rust_action_files(
    expected_path: &Path,
    outputs: &super::native_action_input::LeafOutputs,
    request: &WrapperRequest,
    runner: &mut Runner,
) -> Result<OwnedProduct> {
    let context = ExecutionContext::capture()?;
    with_owned_files_in_context(expected_path, outputs, request, runner, &context)
}

fn with_owned_files_in_context(
    expected_path: &Path,
    outputs: &super::native_action_input::LeafOutputs,
    request: &WrapperRequest,
    runner: &mut Runner,
    context: &ExecutionContext,
) -> Result<OwnedProduct> {
    let mut custody = Custody::new();
    let data = (|| {
        let expected: ExpectedGraph = decode(&custody.bytes(expected_path)?)?;
        let bytes = custody.bytes(&outputs.recipe)?;
        let mut recipes = BTreeMap::new();
        for path in super::native_action_input::declared_recipe_paths(&bytes)? {
            let bytes = custody.bytes(&path)?;
            recipes.insert(path, bytes);
        }
        let declared =
            super::native_action_input::parse_declared_graph(&bytes, &expected, outputs, &recipes)?;
        require(
            declared.leaf.control_inputs.get("expected") == Some(&expected_path.to_path_buf()),
            "actual expected manifest differs from declared owner control",
        )?;
        Ok((expected, declared))
    })();
    match data {
        Ok((expected, declared)) => {
            run_owned_rust_action(&expected, &declared, request, runner, &mut custody, context)
        }
        Err(error) => finish(finish(Err(error), custody.close()), context.close()),
    }
}

/// Entry for the thin native executable. Acquire context before any owned log
/// creation, then use that same snapshot through explicit spawn and final close.
pub fn execute_owned_rust_action_files(
    expected_path: &Path,
    outputs: &super::native_action_input::LeafOutputs,
    wrapper: Vec<String>,
) -> Result<OwnedProduct> {
    use std::os::unix::ffi::OsStringExt;
    let context = ExecutionContext::capture()?;
    let mut retained = None;
    let setup = (|| {
        let metadata = context
            .effective_environment()
            .get("RUST_ACTION_INPUT_METADATA")
            .ok_or("RUST_ACTION_INPUT_METADATA must name the executor input inventory")?;
        require(
            !metadata.is_empty(),
            "RUST_ACTION_INPUT_METADATA must not be empty",
        )?;
        let stamp = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_err(|e| e.to_string())?
            .as_nanos();
        let logs = context.temporary().join(format!(
            "reverie-native-rust-action-{}-{stamp}",
            std::process::id()
        ));
        fs::DirBuilder::new()
            .mode(0o700)
            .create(&logs)
            .map_err(|e| format!("create owned action logs {}: {e}", logs.display()))?;
        retained = Some(logs.clone());
        let runner = Runner::new(
            logs.join("commands"),
            std::time::Duration::from_secs(600),
            64 * 1024 * 1024,
        )?;
        let request = WrapperRequest {
            argv: wrapper,
            cwd: context.cwd().to_owned(),
            executor_metadata: PathBuf::from(std::ffi::OsString::from_vec(metadata.clone())),
        };
        Ok((runner, request))
    })();
    let result = match setup {
        Ok((mut runner, request)) => {
            with_owned_files_in_context(expected_path, outputs, &request, &mut runner, &context)
        }
        Err(error) => finish(Err(error), context.close()),
    };
    result.map_err(|error| match retained {
        Some(logs) => format!("{error}; retained action logs: {}", logs.display()),
        None => error,
    })
}

fn run_owned_rust_action(
    expected: &ExpectedGraph,
    declared: &DeclaredGraph,
    request: &WrapperRequest,
    runner: &mut Runner,
    custody: &mut Custody,
    context: &ExecutionContext,
) -> Result<OwnedProduct> {
    let mut final_marker = None;
    let mut qualified_copy = None;
    let primary = (|| {
        let has_relative = std::iter::once(&declared.leaf)
            .chain(declared.dependencies.values())
            .any(|action| {
                action
                    .files
                    .values()
                    .chain(action.control_inputs.values())
                    .chain([
                        &action.recipe,
                        &action.product,
                        &action.directory,
                        &action.input_inventory,
                        &action.invocation,
                        &action.evidence,
                        &action.finalization,
                    ])
                    .any(|path| path.is_relative())
            });
        if has_relative || request.executor_metadata.is_relative() {
            require(
                fs::canonicalize(&request.cwd).map_err(|e| e.to_string())?
                    == std::env::current_dir().map_err(|e| e.to_string())?,
                "relative native Artifact paths require the wrapper and factory working directories to match",
            )?;
        }
        constructor_code_coverage(expected)?;
        let recipe_bytes = check_recipes(expected, declared, custody, false)?;
        let InputFiles {
            files,
            inventory_paths,
        } = open_inputs(&expected.leaf, &declared.leaf, declared, custody)?;
        let producers = dependencies(expected, declared, custody)?;
        join_consumed(&expected.leaf, &declared.leaf, &files, declared, &producers)?;
        let mut paths = original_paths(&declared.leaf)?;
        paths.insert(
            "$executor_metadata".into(),
            request.executor_metadata.as_os_str().as_bytes().to_vec(),
        );
        executable_inputs(&expected.leaf, &paths, &files)?;
        strict_flat_tools(&expected.leaf, &declared.leaf, &paths, custody)?;
        let controls = open_executing_controls(
            &expected.leaf,
            &expected.dependencies,
            &declared.leaf,
            custody,
        )?;
        let output_paths = if expected.leaf.external_linked_inputs.is_empty() {
            BTreeSet::new()
        } else {
            external_dependency_outputs(declared, custody)?
        };
        external_link_eligibility(
            &expected.leaf,
            &declared.leaf,
            declared,
            &files,
            &paths,
            &controls,
            &output_paths,
        )?;
        let external = owned_external_links(&expected.leaf, &declared.leaf, &request.cwd, custody)?;
        let inventory_bytes = custody.bytes(&request.executor_metadata)?;
        let inventory = check_inventory_with_external(
            &inventory_bytes,
            &files,
            &controls,
            &request.cwd,
            None,
            Some(&inventory_paths),
            &external,
        )?;
        let argv: Vec<_> = request
            .argv
            .iter()
            .map(|arg| arg.as_bytes().to_vec())
            .collect();
        require(
            !request.argv.is_empty()
                && argv == arguments(&expected.leaf.wrapper_argv, &paths)?
                && request.cwd.as_os_str().as_bytes() == argument(&expected.leaf.cwd, &paths)?,
            "whole normal wrapper argv/cwd differs from independent expectation",
        )?;
        // The executed tool must be one of the independently opened inputs.
        let executable =
            fs::canonicalize(request.cwd.join(&request.argv[0])).map_err(|e| e.to_string())?;
        require(
            file_specs(&expected.leaf)?.iter().any(|(id, spec)| {
                spec.produced.is_none() && files.get(id).is_some_and(|file| file.path == executable)
            }),
            "whole-wrapper executable is not a declared pinned tool",
        )?;
        require(
            fs::symlink_metadata(&declared.leaf.product)
                .is_err_and(|error| error.kind() == std::io::ErrorKind::NotFound),
            "owned native product already exists or is inaccessible",
        )?;
        let parent = declared
            .leaf
            .directory
            .parent()
            .ok_or("native owner directory has no parent")?;
        custody.directory(parent)?;
        custody.directory(
            declared
                .leaf
                .product
                .parent()
                .ok_or("native product has no parent")?,
        )?;
        fs::DirBuilder::new()
            .mode(0o700)
            .create(&declared.leaf.directory)
            .map_err(|e| format!("create exclusive native owner directory: {e}"))?;
        custody.directory(&declared.leaf.directory)?;
        write_new(&declared.leaf.input_inventory, &inventory_bytes, custody)?;
        custody.directory(&request.cwd)?;
        custody.directory(&runner.logs)?;
        let environment = wrapper_child_environment(&expected.leaf, &paths, &files, context)?;
        let before = runner.commands.len();
        let outcome = runner.run_with_environment(
            &request.argv[0],
            &request.argv[1..],
            &request.cwd,
            &environment,
        );
        let capture = capture_commands(custody, runner, before);
        finish(outcome, capture)?;
        require(
            runner.commands.len() == before + 1 && runner.commands[before].status == 0,
            "whole normal wrapper did not complete successfully",
        )?;
        let invocation_bytes = custody.bytes(&declared.leaf.invocation)?;
        let invocation = parse_invocation_handoff(&invocation_bytes)?;
        invocation_join(&expected.leaf, &paths, &invocation, &context.observation())?;
        let product = custody.file(&declared.leaf.product)?;
        let qualification = if expected.leaf.selection == "cdylib" {
            let binding = source_binding(
                expected,
                declared,
                &files,
                &producers,
                &product,
                &paths,
                &invocation,
            )?;
            let sources = VerifiedNativeSources::from_checked_action(&binding)?;
            Some(qualify_physical(&product, runner, &sources, custody)?)
        } else {
            None
        };
        if let Some(path) = &declared.leaf.qualified_product {
            let parent = path.parent().ok_or("qualified copy has no parent")?;
            fs::DirBuilder::new()
                .mode(0o700)
                .create(parent)
                .map_err(|e| format!("create qualified directory: {e}"))?;
            custody.directory(parent)?;
            qualified_copy = Some(super::native_action_custody::QualifiedCopy::create(path)?);
            qualified_copy.as_mut().unwrap().write_from(&product)?;
        }
        let record = RetainedProducer {
            kind: if external.is_empty() {
                "reverie-native-compilation/v2"
            } else {
                "reverie-native-compilation/v3"
            }
            .into(),
            role: expected.leaf.role.clone(),
            producer: expected.leaf.producer.clone(),
            configuration: expected.leaf.configuration.clone(),
            selection: expected.leaf.selection.clone(),
            original_inputs: declared
                .leaf
                .files
                .iter()
                .map(|(id, file)| (id.clone(), file.as_os_str().as_bytes().to_vec()))
                .collect(),
            input_sha256: files
                .iter()
                .map(|(id, file)| (id.clone(), file.sha256.clone()))
                .collect(),
            original_product: declared.leaf.product.as_os_str().as_bytes().to_vec(),
            original_directory: declared.leaf.directory.as_os_str().as_bytes().to_vec(),
            wrapper_argv: argv,
            wrapper_environment: environment.clone(),
            context: context.observation(),
            wrapper_cwd: request.cwd.as_os_str().as_bytes().to_vec(),
            wrapper_status: runner.commands[before].status,
            original_executor_metadata: request.executor_metadata.as_os_str().as_bytes().to_vec(),
            input_inventory_sha256: sha256(&inventory_bytes),
            inventory_paths: inventory.paths,
            external_linked_inputs: (!external.is_empty()).then_some(external),
            control_sha256: inventory.control_sha256,
            invocation_sha256: sha256(&invocation_bytes),
            recipe_sha256: sha256(&recipe_bytes),
            product_sha256: product.sha256.clone(),
            dependencies: expected.leaf.dependencies.clone(),
            metadata_dependencies: expected.leaf.metadata_dependencies.clone(),
        };
        let evidence_bytes = serde_json::to_vec(&record).map_err(|e| e.to_string())?;
        let evidence = write_new(&declared.leaf.evidence, &evidence_bytes, custody)?;
        // This includes the source and selected/copied output transactions. The
        // last declared marker is not written on any preceding failure.
        finish(custody.close(), context.close())?;
        let finalization = Finalization {
            kind: "reverie-native-closed/v1".into(),
            evidence_sha256: evidence.sha256.clone(),
            product_sha256: product.sha256.clone(),
        };
        let final_bytes = serde_json::to_vec(&finalization).map_err(|e| e.to_string())?;
        final_marker = Some(super::native_action_custody::FinalMarker::create(
            &declared.leaf.directory,
        )?);
        // Register ownership before any fallible payload write/check so late
        // failure can always withhold our exact marker through the held dirfd.
        final_marker.as_mut().unwrap().write_payload(&final_bytes)?;
        let compilation = Compilation {
            product,
            evidence,
            reused: false,
        };
        Ok(match qualification {
            Some(qualification) => qualification.into_owned(compilation),
            None => OwnedProduct::Compilation(compilation),
        })
    })();
    let marker_close = final_marker
        .as_ref()
        .map_or(Ok(()), |marker| marker.verify());
    let copy_close = qualified_copy.as_ref().map_or(Ok(()), |copy| copy.verify());
    let result = finish(
        finish(
            finish(finish(primary, custody.close()), context.close()),
            marker_close,
        ),
        copy_close,
    );
    match result {
        Ok(value) => Ok(value),
        Err(mut error) => {
            if let Some(marker) = final_marker {
                let cleanup = marker.remove_owned();
                if let Err(cleanup) = cleanup {
                    error.push_str(&format!("; withhold finalization: {cleanup}"));
                }
            }
            if let Some(copy) = qualified_copy {
                let cleanup = copy.remove_owned();
                if let Err(cleanup) = cleanup {
                    error.push_str(&format!("; withhold qualified copy: {cleanup}"));
                }
            }
            Err(error)
        }
    }
}

