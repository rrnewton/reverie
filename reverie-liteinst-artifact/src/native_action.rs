/// Borrowed view valid only within `with_declared_native_entry`.
/// The factory retains all source, product, input and parent custody. Publication
/// guards must be completed only after the enclosing factory returns success.
pub struct NativeEntryScope<'a> {
    qualified: QualifiedNativeEntry,
    sources: &'a VerifiedNativeSources,
    custody: &'a Custody,
}
impl NativeEntryScope<'_> {
    pub fn compilation(&self) -> &Compilation {
        self.qualified.compilation()
    }
    pub fn qualification(&self) -> &NativeEntryQualification {
        self.qualified.qualification()
    }
    /// Recheck at the consumer's physical join. The factory also closes after
    /// the callback, so a later mutation or a callback failure cannot skip close.
    pub fn verify_unchanged(&self) -> Result<()> {
        finish(self.sources.verify_unchanged(), self.custody.close())
    }
}

struct LinkedFileEntry {
    file: FileIdentity,
    inventory_path: PathBuf,
    guard: usize,
}

pub(super) struct Custody {
    files: Vec<OpenedFile>,
    linked_files: Vec<LinkedInputFile>,
    requested_linked_files: BTreeMap<PathBuf, LinkedFileEntry>,
    requested_files: BTreeMap<PathBuf, FileIdentity>,
    directories: Vec<DirectoryGuard>,
    trees: Vec<super::native_action_custody::DirectoryTree>,
}
impl Custody {
    pub(super) fn new() -> Self {
        Self {
            files: Vec::new(),
            linked_files: Vec::new(),
            requested_linked_files: BTreeMap::new(),
            requested_files: BTreeMap::new(),
            directories: Vec::new(),
            trees: Vec::new(),
        }
    }
    fn file(&mut self, path: &Path) -> Result<FileIdentity> {
        // An exact repeated spelling shares its already acquired transaction.
        // Different aliases still acquire their own namespace guards. Every
        // captured guard is checked at close, including on the error path.
        if let Some(file) = self.requested_files.get(path) {
            return Ok(file.clone());
        }
        let expected = FileIdentity::read(path)?;
        let opened = OpenedFile::capture(path, &expected)?;
        self.files.push(opened);
        self.requested_files
            .insert(path.to_owned(), expected.clone());
        Ok(expected)
    }
    fn linked_input(&mut self, path: &Path) -> Result<(FileIdentity, PathBuf)> {
        // Never seed the strict file cache: a later source/tool/output lookup
        // must still reject a leaf alias even when its content was opened here.
        if let Some(file) = self.requested_linked_files.get(path) {
            return Ok((file.file.clone(), file.inventory_path.clone()));
        }
        let opened = LinkedInputFile::capture(path)?;
        let file = (opened.file().clone(), opened.inventory_path().to_owned());
        let guard = self.linked_files.len();
        self.linked_files.push(opened);
        self.requested_linked_files.insert(
            path.to_owned(),
            LinkedFileEntry {
                file: file.0.clone(),
                inventory_path: file.1.clone(),
                guard,
            },
        );
        Ok(file)
    }
    fn external_link(&self, path: &Path, root: &Path) -> Result<ExternalLinkWitness> {
        let acquired = self
            .requested_linked_files
            .get(path)
            .ok_or("external linked input has no acquired linked namespace")?;
        self.linked_files[acquired.guard].external_witness(root)
    }
    fn bytes(&mut self, path: &Path) -> Result<Vec<u8>> {
        let (opened, bytes) = OpenedFile::report(path)?;
        self.requested_files
            .insert(path.to_owned(), opened.file.clone());
        self.files.push(opened);
        Ok(bytes)
    }
    fn directory(&mut self, path: &Path) -> Result<()> {
        self.directories.push(DirectoryGuard::capture(path)?);
        Ok(())
    }
    pub(super) fn close(&self) -> Result<()> {
        let errors: Vec<_> = self
            .files
            .iter()
            .filter_map(|file| file.verify().err())
            .chain(
                self.linked_files
                    .iter()
                    .filter_map(|file| file.verify().err()),
            )
            .chain(self.directories.iter().filter_map(|dir| dir.verify().err()))
            .chain(self.trees.iter().filter_map(|tree| tree.verify().err()))
            .collect();
        if errors.is_empty() {
            Ok(())
        } else {
            Err(errors.join("; "))
        }
    }
}
fn finish<T>(primary: Result<T>, close: Result<()>) -> Result<T> {
    match (primary, close) {
        (Ok(value), Ok(())) => Ok(value),
        (Err(error), Ok(())) => Err(error),
        (Ok(_), Err(error)) => Err(format!("native action close: {error}")),
        (Err(error), Err(close)) => Err(format!("{error}; native action close: {close}")),
    }
}
fn named(value: &str) -> Result<()> {
    require(
        !value.is_empty() && !value.contains('\0'),
        "empty or NUL native role/identity",
    )
}
fn original_paths(declared: &DeclaredProducer) -> Result<BTreeMap<String, Vec<u8>>> {
    let mut paths: BTreeMap<_, _> = declared
        .files
        .iter()
        .map(|(id, file)| (id.clone(), file.as_os_str().as_bytes().to_vec()))
        .collect();
    require(
        paths
            .insert(
                "$product".into(),
                declared.product.as_os_str().as_bytes().to_vec(),
            )
            .is_none()
            && paths
                .insert(
                    "$directory".into(),
                    declared.directory.as_os_str().as_bytes().to_vec(),
                )
                .is_none(),
        "reserved native output logical ID used as input",
    )?;
    validate_paths(&paths)?;
    Ok(paths)
}
fn validate_paths(paths: &BTreeMap<String, Vec<u8>>) -> Result<()> {
    for (id, path) in paths {
        named(id)?;
        require(
            !path.is_empty() && !path.contains(&0),
            "empty or NUL original artifact path",
        )?;
    }
    Ok(())
}
fn retained_paths(
    record: &RetainedProducer,
    declared: &DeclaredProducer,
) -> Result<BTreeMap<String, Vec<u8>>> {
    require(
        record.original_inputs.keys().eq(declared.files.keys()),
        "retained logical input set differs from current declared producer",
    )?;
    let mut paths = record.original_inputs.clone();
    paths.insert(
        "$executor_metadata".into(),
        record.original_executor_metadata.clone(),
    );
    require(
        paths
            .insert("$product".into(), record.original_product.clone())
            .is_none()
            && paths
                .insert("$directory".into(), record.original_directory.clone())
                .is_none(),
        "reserved logical input ID",
    )?;
    validate_paths(&paths)?;
    Ok(paths)
}

fn argument(parts: &Argument, paths: &BTreeMap<String, Vec<u8>>) -> Result<Vec<u8>> {
    require(!parts.is_empty(), "empty native argument composition")?;
    let mut value = Vec::new();
    for part in parts {
        match part {
            ArgumentPart::ExecutionContext { .. } => {
                return Err(
                    "execution context reference is only valid in its environment slot".into(),
                );
            }
            ArgumentPart::Literal { bytes } => value.extend_from_slice(bytes),
            ArgumentPart::Artifact { id } if id == "$executor_metadata" => {
                return Err("executor metadata path is only valid in its environment slot".into());
            }
            ArgumentPart::Artifact { id } => value.extend_from_slice(
                paths
                    .get(id)
                    .ok_or_else(|| format!("undeclared logical artifact in argument: {id}"))?,
            ),
        }
    }
    require(!value.contains(&0), "NUL in native argument")?;
    Ok(value)
}
fn environment_arguments(
    wanted: &BTreeMap<String, Argument>,
    paths: &BTreeMap<String, Vec<u8>>,
    context: &ContextObservation,
) -> Result<BTreeMap<String, Vec<u8>>> {
    context.validate()?;
    let mut result = BTreeMap::new();
    for (name, value) in wanted {
        named(name)?;
        if let [ArgumentPart::ExecutionContext { slot }] = value.as_slice() {
            require(
                name == slot.name(),
                "execution context reference is not in its closed environment slot",
            )?;
            if let Some(bytes) = context.resolve(*slot)? {
                result.insert(name.clone(), bytes.to_vec());
            }
        } else if matches!(value.as_slice(), [ArgumentPart::Artifact { id }] if id == "$executor_metadata")
        {
            require(
                name == "RUST_ACTION_INPUT_METADATA",
                "executor metadata reference is not in its exact environment slot",
            )?;
            result.insert(
                name.clone(),
                paths
                    .get("$executor_metadata")
                    .ok_or("guarded executor metadata input path absent")?
                    .clone(),
            );
        } else {
            result.insert(name.clone(), argument(value, paths)?);
        }
    }
    Ok(result)
}

fn context_environment(
    context: &ContextObservation,
    environment: &BTreeMap<String, Vec<u8>>,
) -> Result<()> {
    context.validate()?;
    for (slot, value) in &context.slots {
        require(
            environment.get(slot.name()).map(Vec::as_slice) == value.as_deref(),
            "retained execution context differs from whole-wrapper environment",
        )?;
    }
    Ok(())
}

fn environment_tool(
    tool: &EnvironmentTool,
    expected: &ExpectedProducer,
    paths: &BTreeMap<String, Vec<u8>>,
    files: &BTreeMap<String, FileIdentity>,
) -> Result<Vec<u8>> {
    let root = expected
        .files
        .get(&tool.input)
        .ok_or("environment tool input absent")?;
    let mut path = paths
        .get(&tool.input)
        .ok_or("environment tool path absent")?
        .clone();
    let (id, spec) = if let Some(member) = &tool.member {
        let id = member_id(&tool.input, member)?;
        let spec = root
            .directory_members
            .as_ref()
            .and_then(|members| members.get(member))
            .ok_or("environment tool is not an explicit directory member")?;
        if !path.ends_with(b"/") {
            path.push(b'/');
        }
        path.extend_from_slice(member.as_os_str().as_bytes());
        (id, spec)
    } else {
        (tool.input.clone(), root)
    };
    require(
        root.produced.is_none()
            && spec.produced.is_none()
            && spec.directory_members.is_none()
            && files
                .get(&id)
                .is_some_and(|file| file.sha256 == spec.sha256),
        "environment tool is not an independently pinned regular input",
    )?;
    Ok(path)
}

// A bare executable name is resolved through PATH by process launch, even
// when a different cwd file has the same spelling and independently pinned
// bytes. Only an explicit path binds the checked file to the invoked program.
fn direct_tool_spelling(executable: &[u8]) -> Result<()> {
    require(
        executable.contains(&b'/') && !executable.contains(&0),
        "native executable must use an absolute or explicit relative path; PATH lookup is unsupported",
    )
}

// This is an opt-in contract for the already guarded direct launcher, not a
// general environment-filter callback. A changed tool pin requires the caller
// to re-establish its complete source-backed inherited consumer description.
fn environment_contract(
    expected: &ExpectedProducer,
    paths: &BTreeMap<String, Vec<u8>>,
    files: &BTreeMap<String, FileIdentity>,
) -> Result<()> {
    let Some(contract) = &expected.wrapper_environment_contract else {
        return Ok(());
    };
    for name in contract
        .inherited_names
        .iter()
        .chain(&contract.inherited_prefixes)
    {
        require(
            !name.is_empty()
                && name
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_'),
            "invalid pinned wrapper environment name or prefix",
        )?;
    }
    require(
        contract
            .inherited_prefixes
            .iter()
            .all(|prefix| prefix.len() > 1 && prefix.ends_with('_')),
        "pinned wrapper environment prefix must end in underscore",
    )?;
    let launcher = environment_tool(&contract.launcher, expected, paths, files)?;
    direct_tool_spelling(&launcher)?;
    let script = environment_tool(&contract.script, expected, paths, files)?;
    let argv = arguments(&expected.wrapper_argv, paths)?;
    require(
        argv.first() == Some(&launcher)
            && !script.starts_with(b"-")
            && (argv.get(1) == Some(&script)
                || (argv.get(1).is_some_and(|arg| arg == b"-B") && argv.get(2) == Some(&script))),
        "environment contract requires its exact pinned direct Python launcher and script",
    )
}

fn wrapper_child_environment(
    expected: &ExpectedProducer,
    paths: &BTreeMap<String, Vec<u8>>,
    files: &BTreeMap<String, FileIdentity>,
    context: &ExecutionContext,
) -> Result<BTreeMap<String, Vec<u8>>> {
    let wanted =
        environment_arguments(&expected.wrapper_environment, paths, &context.observation())?;
    environment_contract(expected, paths, files)?;
    let environment = if let Some(contract) = &expected.wrapper_environment_contract {
        // Python startup precedes the script's environment filter. Keep the
        // concrete launcher contract closed, including future PYTHON/loader/
        // locale controls, so an incomplete caller list cannot discard them.
        let mut consumed = contract.inherited_names.clone();
        consumed.extend(
            [
                "LANG",
                "LANGUAGE",
                "PATH",
                "HOME",
                "GLIBC_TUNABLES",
                "GCONV_PATH",
                "LOCPATH",
                "NLSPATH",
                "TZ",
                "TZDIR",
                "__PYVENV_LAUNCHER__",
            ]
            .into_iter()
            .map(str::to_owned),
        );
        let mut prefixes = contract.inherited_prefixes.clone();
        prefixes.extend(
            ["PYTHON", "LD_", "DYLD_", "LC_"]
                .into_iter()
                .map(str::to_owned),
        );
        context.select_environment(
            &wanted,
            &BTreeSet::from(["LANG".into(), "PYTHONUNBUFFERED".into()]),
            &consumed,
            &prefixes,
        )?
    } else {
        require(
            context.effective_environment() == &wanted,
            "whole-wrapper effective environment differs",
        )?;
        wanted
    };
    // Both modes preserve the exact six captured values, including absence,
    // before the child exists. Retained checks use the original observation.
    context_environment(&context.observation(), &environment)?;
    Ok(environment)
}

fn arguments(parts: &[Argument], paths: &BTreeMap<String, Vec<u8>>) -> Result<Vec<Vec<u8>>> {
    parts.iter().map(|part| argument(part, paths)).collect()
}
fn declare_join(expected: &ExpectedProducer, declared: &DeclaredProducer) -> Result<()> {
    for name in [
        &expected.role,
        &expected.producer,
        &expected.configuration,
        &expected.crate_name,
    ] {
        named(name)?;
    }
    require(
        expected.role == declared.role
            && expected.producer == declared.producer
            && expected.configuration == declared.configuration
            && expected.selection == declared.selection,
        "declared producer/configuration/role/selection differs from expectation",
    )?;
    require(
        matches!(
            expected.selection.as_str(),
            "cdylib" | "code-rlib-static_pic" | "staticlib"
        ),
        "native factory requires a selected cdylib, code rlib or private staticlib",
    )?;
    if expected.selection == "staticlib" {
        require_static_producer(expected)?;
        require(
            declared.metadata_full.is_none(),
            "private staticlib cannot substitute a metadata companion",
        )?;
    }
    require(
        expected.files.keys().eq(declared.files.keys())
            && expected.dependencies == declared.dependencies
            && expected.metadata_dependencies == declared.metadata_dependencies,
        "complete native input/dependency association differs from expectation",
    )?;
    for id in expected
        .dependencies
        .keys()
        .chain(expected.metadata_dependencies.keys())
    {
        require(
            expected.files.contains_key(id),
            "consumed dependency is not a declared input",
        )?;
    }
    require(
        declared.input_inventory == declared.directory.join("input_inventory.json")
            && declared.invocation == declared.directory.join("invocation.json")
            && declared.evidence == declared.directory.join("evidence.json")
            && declared.finalization == declared.directory.join("finalization.json")
            && match &declared.qualified_product {
                Some(product) => {
                    expected.selection == "cdylib"
                        && product.parent() == Some(declared.directory.join("qualified").as_path())
                }
                None => matches!(
                    expected.selection.as_str(),
                    "code-rlib-static_pic" | "staticlib"
                ),
            },
        "declared native output association is outside its exact owner directory",
    )?;
    original_paths(declared)?;
    Ok(())
}
fn member_id(id: &str, relative: &Path) -> Result<String> {
    require(
        !relative.as_os_str().is_empty()
            && relative
                .components()
                .all(|part| matches!(part, std::path::Component::Normal(_))),
        "directory member is not an explicit relative path",
    )?;
    Ok(format!(
        "$member:{}",
        serde_json::to_string(&(id, relative)).map_err(|e| e.to_string())?
    ))
}
fn file_specs(expected: &ExpectedProducer) -> Result<Vec<(String, &ExpectedFile)>> {
    let mut result = Vec::new();
    for (id, wanted) in &expected.files {
        require(!id.starts_with('$'), "reserved native logical input ID")?;
        if wanted.produced.is_some() {
            require(
                wanted.directory_members.is_none()
                    && wanted.sha256.is_empty()
                    && wanted.size == 0
                    && wanted.source_key.is_none()
                    && wanted.compiler_filename.is_none(),
                "produced input cannot supply independent bytes or source/compiler authority",
            )?;
        }
        if let Some(members) = &wanted.directory_members {
            require(
                wanted.sha256.is_empty()
                    && wanted.size == 0
                    && wanted.source_key.is_none()
                    && wanted.compiler_filename.is_none(),
                "directory expectation must specify complete members, not file bytes",
            )?;
            for (relative, member) in members {
                require(
                    member.directory_members.is_none() && member.produced.is_none(),
                    "directory member expectation must name a regular file",
                )?;
                result.push((member_id(id, relative)?, member));
            }
        } else {
            result.push((id.clone(), wanted));
        }
    }
    Ok(result)
}
fn check_file(id: &str, wanted: &ExpectedFile, file: &FileIdentity) -> Result<()> {
    require(
        wanted.sha256.len() == 64
            && wanted
                .sha256
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)),
        "invalid independent native input digest",
    )?;
    require(
        file.sha256 == wanted.sha256
            && fs::metadata(&file.path).map_err(|e| e.to_string())?.len() == wanted.size,
        format!("native input differs from independent bytes: {id}"),
    )
}
fn produced_path<'a>(produced: &ProducedArtifact, graph: &'a DeclaredGraph) -> Result<&'a Path> {
    let producer = graph
        .dependencies
        .get(&produced.role)
        .ok_or("produced input has no normal declared producer role")?;
    Ok(match produced.output {
        ProducerOutput::Product => &producer.product,
        ProducerOutput::MetadataFull => producer
            .metadata_full
            .as_ref()
            .ok_or("produced metadata companion is absent")?,
        ProducerOutput::Recipe => &producer.recipe,
        ProducerOutput::Invocation => &producer.invocation,
        ProducerOutput::Evidence => &producer.evidence,
        ProducerOutput::Finalization => &producer.finalization,
        ProducerOutput::Directory => &producer.directory,
        ProducerOutput::InputInventory => &producer.input_inventory,
        ProducerOutput::ExpectedInputs => &producer.control_inputs["expected"],
        ProducerOutput::OwnerExecutable => &producer.control_inputs["owner"],
    })
}
fn produced_directory_members(
    produced: &ProducedArtifact,
    graph: &DeclaredGraph,
) -> Result<BTreeSet<PathBuf>> {
    let producer = &graph.dependencies[&produced.role];
    require(
        producer.selection == "code-rlib-static_pic" && producer.qualified_product.is_none(),
        "produced dependency directory is not the normal compilation-only association",
    )?;
    Ok(BTreeSet::from([
        PathBuf::from("input_inventory.json"),
        PathBuf::from("invocation.json"),
        PathBuf::from("evidence.json"),
        PathBuf::from("finalization.json"),
    ]))
}

fn check_tree_members(
    guard: &super::native_action_custody::DirectoryTree,
    actual: &BTreeMap<PathBuf, FileIdentity>,
) -> Result<()> {
    for member in guard.regular_members() {
        require(
            member.root.is_absolute()
                && member
                    .relative
                    .components()
                    .all(|part| matches!(part, std::path::Component::Normal(_)))
                && member.mode & libc::S_IFMT == libc::S_IFREG
                && actual.get(member.relative) == Some(member.target),
            "guarded physical root/member/target association differs",
        )?;
    }
    Ok(())
}

struct InputFiles {
    files: BTreeMap<String, FileIdentity>,
    inventory_paths: BTreeMap<String, PathBuf>,
}

fn open_inputs(
    expected: &ExpectedProducer,
    declared: &DeclaredProducer,
    graph: &DeclaredGraph,
    custody: &mut Custody,
) -> Result<InputFiles> {
    declare_join(expected, declared)?;
    file_specs(expected)?;
    let mut files = BTreeMap::new();
    let mut inventory_paths = BTreeMap::new();
    for (id, wanted) in &expected.files {
        if let Some(produced) = &wanted.produced {
            require(
                declared.files[id] == produced_path(produced, graph)?,
                "produced logical input differs from its exact typed producer output",
            )?;
            if produced.output == ProducerOutput::Directory {
                let (guard, actual) =
                    super::native_action_custody::DirectoryTree::capture(&declared.files[id])?;
                check_tree_members(&guard, &actual)?;
                custody.trees.push(guard);
                require(
                    actual.keys().cloned().collect::<BTreeSet<_>>()
                        == produced_directory_members(produced, graph)?,
                    "produced directory differs from exact companion output membership",
                )?;
                for (relative, file) in actual {
                    files.insert(member_id(id, &relative)?, file);
                }
            } else {
                files.insert(id.clone(), custody.file(&declared.files[id])?);
            }
        } else if let Some(members) = &wanted.directory_members {
            let (guard, actual) =
                super::native_action_custody::DirectoryTree::capture(&declared.files[id])?;
            check_tree_members(&guard, &actual)?;
            custody.trees.push(guard);
            require(
                members.keys().eq(actual.keys()),
                format!("complete directory membership differs: {id}"),
            )?;
            for (relative, member) in members {
                let key = member_id(id, relative)?;
                check_file(&key, member, &actual[relative])?;
                files.insert(key, actual[relative].clone());
            }
        } else {
            let path = &declared.files[id];
            // Legacy wrappers do not declare which non-executable argv inputs
            // are startup scripts. Keep their old strict flat-file contract;
            // only the pinned direct launcher/script contract can admit aliases.
            let (file, inventory_path) = if expected.wrapper_environment_contract.is_some()
                && declared.linked_inputs.get(id) == Some(path)
                && wanted.source_key.is_none()
                && wanted.compiler_filename.is_none()
                && !expected.dependencies.contains_key(id)
                && !expected.metadata_dependencies.contains_key(id)
                && !graph.dependencies.values().any(|producer| {
                    producer.product == *path || producer.metadata_full.as_ref() == Some(path)
                }) {
                custody.linked_input(path)?
            } else {
                let file = custody.file(path)?;
                let inventory_path = file.path.clone();
                (file, inventory_path)
            };
            check_file(id, wanted, &file)?;
            inventory_paths.insert(id.clone(), inventory_path);
            files.insert(id.clone(), file);
        }
    }
    for (id, file) in &files {
        inventory_paths
            .entry(id.clone())
            .or_insert_with(|| file.path.clone());
    }
    Ok(InputFiles {
        files,
        inventory_paths,
    })
}

// Controls are the producer owner, independent manifest and this action's recipe.
// They are guarded inputs, but cannot require the manifest to hash itself.
fn open_controls(
    expected: &ExpectedProducer,
    dependencies: &BTreeMap<String, ExpectedProducer>,
    declared: &DeclaredProducer,
    custody: &mut Custody,
) -> Result<BTreeMap<String, FileIdentity>> {
    require(
        declared
            .control_inputs
            .keys()
            .map(String::as_str)
            .collect::<BTreeSet<_>>()
            == BTreeSet::from(["owner", "expected"]),
        "native owner control input roles differ",
    )?;
    let manifest_bytes = custody.bytes(&declared.control_inputs["expected"])?;
    let manifest: ExpectedGraph = decode(&manifest_bytes)?;
    require(
        manifest.leaf == *expected,
        "producer expected control differs from independent role/cohort requirements",
    )?;
    require(
        manifest.dependencies == *dependencies,
        "producer expected control dependency map differs from independent graph",
    )?;
    let owner = custody.file(&declared.control_inputs["owner"])?;
    if let Some(pin) = &expected.owner_pin {
        require(
            pin.sha256.len() == 64
                && pin
                    .sha256
                    .bytes()
                    .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)),
            "invalid independent native owner digest",
        )?;
        require(
            owner.sha256 == pin.sha256
                && fs::metadata(&owner.path).map_err(|e| e.to_string())?.len() == pin.size,
            "native owner control differs from independent bytes",
        )?;
    }
    let result = BTreeMap::from([
        ("$control:owner".into(), owner),
        (
            "$control:expected".into(),
            custody.file(&declared.control_inputs["expected"])?,
        ),
        ("$control:recipe".into(), custody.file(&declared.recipe)?),
    ]);
    // Keep these reserved IDs outside the source/argument namespace.
    require(result.len() == 3, "duplicate native owner control")?;
    Ok(result)
}

fn require_current_owner(
    controls: &BTreeMap<String, FileIdentity>,
    custody: &mut Custody,
) -> Result<()> {
    let running = custody.file(&std::env::current_exe().map_err(|e| e.to_string())?)?;
    require(
        controls["$control:owner"].sha256 == running.sha256,
        "declared owner control is not the executing factory",
    )
}

fn open_executing_controls(
    expected: &ExpectedProducer,
    dependencies: &BTreeMap<String, ExpectedProducer>,
    declared: &DeclaredProducer,
    custody: &mut Custody,
) -> Result<BTreeMap<String, FileIdentity>> {
    let controls = open_controls(expected, dependencies, declared, custody)?;
    require_current_owner(&controls, custody)?;
    Ok(controls)
}

fn open_retained_controls(
    expected: &ExpectedProducer,
    dependencies: &BTreeMap<String, ExpectedProducer>,
    declared: &DeclaredProducer,
    custody: &mut Custody,
) -> Result<BTreeMap<String, FileIdentity>> {
    let controls = open_controls(expected, dependencies, declared, custody)?;
    // Legacy same-executable consumers retain their original check. A foreign
    // consumer has no default exemption: its owner must pass the independent pin.
    if expected.owner_pin.is_none() {
        require_current_owner(&controls, custody)?;
    }
    Ok(controls)
}

fn external_input_ids<'de, D: serde::Deserializer<'de>>(
    deserializer: D,
) -> std::result::Result<BTreeSet<String>, D::Error> {
    let ids = Vec::<String>::deserialize(deserializer)?;
    let unique: BTreeSet<_> = ids.iter().cloned().collect();
    if unique.len() != ids.len() {
        return Err(serde::de::Error::custom(
            "duplicate external linked input ID",
        ));
    }
    Ok(unique)
}

fn normal_external_relative(path: &Path, empty: bool) -> Result<()> {
    let text = path.to_str().ok_or("external link path is not UTF-8")?;
    require(
        (empty && text.is_empty())
            || (!text.is_empty()
                && text.len() <= super::native_executor_inputs::MAX_INVENTORY_PATH_BYTES
                && !text.starts_with('/')
                && !(text.as_bytes().first().is_some_and(u8::is_ascii_alphabetic)
                    && text.as_bytes().get(1) == Some(&b':'))
                && !text.contains(['\0', '\\'])
                && text
                    .split('/')
                    .all(|part| !part.is_empty() && part != "." && part != "..")),
        "external link path is not an exact project-relative spelling",
    )
}

fn external_witness_shape(witness: &ExternalLinkWitness) -> Result<()> {
    normal_external_relative(&witness.requested, false)?;
    normal_external_relative(&witness.link, false)?;
    normal_external_relative(&witness.remaining, true)?;
    require(
        witness.target.is_absolute()
            && !witness.target.as_os_str().as_bytes().contains(&0)
            && witness.target.as_os_str().len()
                <= super::native_executor_inputs::MAX_INVENTORY_PATH_BYTES
            && witness.link.join(&witness.remaining) == witness.requested,
        "external link target or original prefix/suffix association differs",
    )
}

// This classification applies only to ordinary linked bytes. Other roles keep
// their required File observation even if another logical ID aliases them.
fn external_dependency_outputs(
    graph: &DeclaredGraph,
    custody: &mut Custody,
) -> Result<BTreeSet<PathBuf>> {
    let mut outputs = BTreeSet::new();
    for producer in graph.dependencies.values() {
        for path in std::iter::once(&producer.product).chain(producer.metadata_full.iter()) {
            outputs.insert(custody.file(path)?.path);
        }
    }
    Ok(outputs)
}

fn external_link_eligibility(
    expected: &ExpectedProducer,
    declared: &DeclaredProducer,
    graph: &DeclaredGraph,
    files: &BTreeMap<String, FileIdentity>,
    paths: &BTreeMap<String, Vec<u8>>,
    controls: &BTreeMap<String, FileIdentity>,
    outputs: &BTreeSet<PathBuf>,
) -> Result<()> {
    if expected.external_linked_inputs.is_empty() {
        return Ok(());
    }
    require(
        expected.wrapper_environment_contract.is_some()
            && matches!(expected.selection.as_str(), "cdylib" | "staticlib"),
        "external linked inputs require the explicit linking wrapper contract",
    )?;
    declared_link_coverage(expected, declared, graph)?;
    let mut protected: BTreeSet<_> = controls.values().map(|file| file.path.clone()).collect();
    protected.extend(outputs.iter().cloned());
    let mut tool_paths = BTreeSet::new();
    for command in [&expected.wrapper_argv, &expected.compiler_argv] {
        tool_paths.insert(argument(
            command.first().ok_or("native tool invocation is empty")?,
            paths,
        )?);
    }
    if let Some(contract) = &expected.wrapper_environment_contract {
        for tool in [&contract.launcher, &contract.script] {
            let id = match &tool.member {
                Some(member) => member_id(&tool.input, member)?,
                None => tool.input.clone(),
            };
            protected.insert(
                files
                    .get(&id)
                    .ok_or("external tool identity absent")?
                    .path
                    .clone(),
            );
            tool_paths.insert(environment_tool(tool, expected, paths, files)?);
        }
    }
    for (id, spec) in &expected.files {
        if let Some(produced) = spec
            .produced
            .as_ref()
            .filter(|produced| produced.output == ProducerOutput::Directory)
        {
            for relative in produced_directory_members(produced, graph)? {
                protected.insert(files[&member_id(id, &relative)?].path.clone());
            }
        } else if let Some(members) = &spec.directory_members {
            for relative in members.keys() {
                // Declared directory members retain their complete File mapping.
                protected.insert(files[&member_id(id, relative)?].path.clone());
            }
        } else {
            let file = files.get(id).ok_or("external input file identity absent")?;
            if spec.produced.is_some()
                || spec.source_key.is_some()
                || spec.compiler_filename.is_some()
                || expected.dependencies.contains_key(id)
                || expected.metadata_dependencies.contains_key(id)
                || paths.get(id).is_some_and(|path| tool_paths.contains(path))
            {
                protected.insert(file.path.clone());
            }
        }
    }
    for id in &expected.external_linked_inputs {
        let spec = expected
            .files
            .get(id)
            .ok_or("external linked input lacks independent pin")?;
        let current = declared
            .files
            .get(id)
            .ok_or("external linked input lacks current Artifact")?;
        require(
            declared.linked_inputs.get(id) == Some(current)
                && spec.produced.is_none()
                && spec.directory_members.is_none()
                && spec.source_key.is_none()
                && spec.compiler_filename.is_none()
                && !expected.dependencies.contains_key(id)
                && !expected.metadata_dependencies.contains_key(id)
                && !protected.contains(&files[id].path)
                && !graph.dependencies.values().any(|producer| {
                    producer.product == *current || producer.metadata_full.as_ref() == Some(current)
                })
                && ![
                    &declared.recipe,
                    &declared.product,
                    &declared.directory,
                    &declared.invocation,
                    &declared.evidence,
                    &declared.finalization,
                    &declared.input_inventory,
                ]
                .contains(&current)
                && declared.qualified_product.as_ref() != Some(current)
                && declared.metadata_full.as_ref() != Some(current),
            "external representation is not an ordinary independently pinned linked input",
        )?;
        check_file(id, spec, &files[id])?;
    }
    Ok(())
}

fn owned_external_links(
    expected: &ExpectedProducer,
    declared: &DeclaredProducer,
    root: &Path,
    custody: &Custody,
) -> Result<BTreeMap<String, ExternalLinkWitness>> {
    expected
        .external_linked_inputs
        .iter()
        .map(|id| {
            let witness = custody.external_link(&declared.files[id], root)?;
            external_witness_shape(&witness)?;
            Ok((id.clone(), witness))
        })
        .collect()
}

fn decode_retained(bytes: &[u8]) -> Result<RetainedProducer> {
    let value = super::native_wire::parse(bytes, super::native_results::MAX_REPORT_BYTES)?;
    let object = value
        .as_object()
        .ok_or("native retained record is not an object")?;
    match object.get("kind").and_then(serde_json::Value::as_str) {
        Some("reverie-native-compilation/v2") => require(
            !object.contains_key("external_linked_inputs"),
            "v2 native evidence cannot carry external input representation",
        )?,
        Some("reverie-native-compilation/v3") => require(
            object
                .get("external_linked_inputs")
                .and_then(serde_json::Value::as_object)
                .is_some_and(|entries| !entries.is_empty()),
            "v3 native evidence requires explicit external input representation",
        )?,
        _ => return Err("unsupported native compilation representation".into()),
    }
    serde_json::from_value(value).map_err(|error| format!("native action record: {error}"))
}

fn retained_external_links(
    expected: &ExpectedProducer,
    record: &RetainedProducer,
) -> Result<BTreeMap<String, ExternalLinkWitness>> {
    let external = record.external_linked_inputs.clone().unwrap_or_default();
    require(
        external.keys().eq(expected.external_linked_inputs.iter())
            && (external.is_empty() == (record.kind == "reverie-native-compilation/v2")),
        "original external input category differs from independent expectations",
    )?;
    if external.is_empty() {
        return Ok(external);
    }
    let cwd = Path::new(
        std::str::from_utf8(&record.wrapper_cwd)
            .map_err(|_| "original external input project root is not UTF-8")?,
    );
    require(
        cwd.is_absolute(),
        "original external input project root is not absolute",
    )?;
    for (id, witness) in &external {
        external_witness_shape(witness)?;
        let original = Path::new(
            std::str::from_utf8(
                record
                    .original_inputs
                    .get(id)
                    .ok_or("original external input association absent")?,
            )
            .map_err(|_| "original external input path is not UTF-8")?,
        );
        let requested = if original.is_absolute() {
            cwd.join(&witness.requested)
        } else {
            witness.requested.clone()
        };
        require(
            original.as_os_str() == requested.as_os_str(),
            "original external input witness differs from guarded recipe spelling",
        )?;
        require(
            record.inventory_paths.get(id).map(|path| path.as_os_str())
                == Some(witness.requested.as_os_str()),
            "original external inventory association differs",
        )?;
    }
    Ok(external)
}

