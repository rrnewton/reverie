/// Exact argument composition. Artifact substitutions use explicit logical IDs,
/// never filename suffixes or recorded absolute-path fallback.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", deny_unknown_fields)]
pub enum ArgumentPart {
    Literal { bytes: Vec<u8> },
    Artifact { id: String },
    ExecutionContext { slot: ContextSlot },
}
pub type Argument = Vec<ArgumentPart>;

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Profile {
    pub opt_level: String,
    pub debuginfo: u32,
    pub debug_assertions: bool,
    pub overflow_checks: bool,
    pub test: bool,
}

